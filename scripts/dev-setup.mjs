// Creates local development and test settings with freshly generated random
// secrets. Run from the repository root: `npm run setup:dev`.
//
// - Never overwrites or changes an existing value, so it is safe to run again.
//   When a newer version of Lexora needs a new setting, running it again adds
//   only the missing lines to existing env files.
// - Never prints a secret.
// - Everything it writes is ignored by Git (see .gitignore).
import { randomBytes } from "node:crypto";
import {
  appendFileSync,
  chmodSync,
  existsSync,
  mkdirSync,
  readFileSync,
  writeFileSync,
} from "node:fs";
import { dirname, join } from "node:path";
import { parseEnv } from "node:util";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const DB_PORT = 55432;

const SECRET_FILES = [
  join("secrets", "postgres_superuser_password"),
  join("secrets", "lexora_owner_password"),
  join("secrets", "lexora_app_password"),
];
const ENV_FILES = {
  development: join("apps", "api", ".env"),
  test: join("apps", "api", ".env.test"),
};

const exists = (relativePath) => existsSync(join(root, relativePath));

/**
 * File permissions (they matter on Linux and macOS; Windows ignores them):
 *
 * - Env files: 0600, read only by you.
 * - Secret files: 0644 inside a 0700 `secrets/` folder. Docker mounts each
 *   secret file into the database container as-is, where PostgreSQL's init
 *   script runs as the container's `postgres` user, not as you; a 0600 file
 *   would be unreadable there and the database roles would not be created.
 *   The 0700 folder still stops other users on this machine from reading
 *   them.
 */
const SECRET_MODE = 0o644;
const ENV_MODE = 0o600;

function write(relativePath, content, mode) {
  const path = join(root, relativePath);
  mkdirSync(dirname(path), { recursive: true });
  // "wx" fails if the file appeared in the meantime: never overwrite.
  writeFileSync(path, content, { encoding: "utf8", mode, flag: "wx" });
  // The mode given above is reduced by the umask; set it exactly.
  chmodSync(path, mode);
  console.log(`created  ${relativePath}`);
}

/** 32 random bytes, URL-safe so it can sit inside a connection string. */
const newPassword = () => randomBytes(32).toString("base64url");
/** 32 random bytes, standard base64, for encryption keys. */
const newKey = () => randomBytes(32).toString("base64");

const url = (user, password, database) =>
  `postgresql://${user}:${password}@127.0.0.1:${DB_PORT}/${database}`;

/** Settings added after the first release of this script, per environment. */
function laterSettings(environment) {
  return [
    {
      key: "APP_ORIGIN",
      lines: [
        "# Origin of the web app; requests from other origins are refused.",
        `APP_ORIGIN=${environment === "test" ? "http://127.0.0.1:4173" : "http://127.0.0.1:5173"}`,
      ],
    },
    {
      key: "MFA_ENCRYPTION_KEY",
      lines: [
        "# Encrypts second-factor secrets (32 bytes, base64).",
        `MFA_ENCRYPTION_KEY=${newKey()}`,
      ],
    },
    ...(environment === "test"
      ? [
          {
            key: "ARGON2_MEMORY_KIB",
            lines: [
              "# Tests use the OWASP minimum Argon2id cost (the floor the API enforces) to run fast.",
              "ARGON2_MEMORY_KIB=19456",
              "ARGON2_ITERATIONS=2",
            ],
          },
        ]
      : []),
  ];
}

function apiEnv({ environment, logLevel, database, appPassword, ownerPassword }) {
  return [
    "# Generated by `npm run setup:dev`. Ignored by Git. Do not commit.",
    `NODE_ENV=${environment}`,
    "HOST=127.0.0.1",
    "PORT=3000",
    `LOG_LEVEL=${logLevel}`,
    "TRUST_PROXY=0",
    "",
    "# Least-privilege application role, used by the running API.",
    `DATABASE_URL=${url("lexora_app", appPassword, database)}`,
    "",
    "# Schema owner role, used only by migration commands.",
    `MIGRATION_DATABASE_URL=${url("lexora_owner", ownerPassword, database)}`,
    `SHADOW_DATABASE_URL=${url("lexora_owner", ownerPassword, "lexora_shadow")}`,
    "",
    ...laterSettings(environment).flatMap((setting) => [...setting.lines, ""]),
  ].join("\n");
}

/** Appends settings missing from an existing env file. Existing lines are never touched. */
function addMissingSettings(environment, relativePath) {
  const path = join(root, relativePath);
  const current = parseEnv(readFileSync(path, "utf8"));
  const missing = laterSettings(environment).filter(
    (setting) => current[setting.key] === undefined,
  );
  if (missing.length === 0) return;
  appendFileSync(path, `\n${missing.flatMap((setting) => [...setting.lines, ""]).join("\n")}`);
  chmodSync(path, ENV_MODE);
  console.log(
    `updated  ${relativePath} (added ${missing.map((setting) => setting.key).join(", ")})`,
  );
}

const allFiles = [...SECRET_FILES, ...Object.values(ENV_FILES)];
const existing = allFiles.filter(exists);

if (existing.length === allFiles.length) {
  for (const [environment, file] of Object.entries(ENV_FILES)) {
    addMissingSettings(environment, file);
  }
  console.log("Development settings are complete.");
  process.exit(0);
}

if (existing.length > 0) {
  console.error(
    "Development settings are incomplete. These files exist:\n" +
      existing.map((file) => `  ${file}`).join("\n") +
      "\nThe passwords in them must match the ones inside the development database, so\n" +
      "this script will not create the missing files. See README.md, section\n" +
      '"Resetting the development database".',
  );
  process.exit(1);
}

const superuserPassword = newPassword();
const ownerPassword = newPassword();
const appPassword = newPassword();

const secretsDir = join(root, "secrets");
mkdirSync(secretsDir, { recursive: true });
chmodSync(secretsDir, 0o700);

write(SECRET_FILES[0], superuserPassword, SECRET_MODE);
write(SECRET_FILES[1], ownerPassword, SECRET_MODE);
write(SECRET_FILES[2], appPassword, SECRET_MODE);
write(
  ENV_FILES.development,
  apiEnv({
    environment: "development",
    logLevel: "debug",
    database: "lexora_dev",
    appPassword,
    ownerPassword,
  }),
  ENV_MODE,
);
write(
  ENV_FILES.test,
  apiEnv({
    environment: "test",
    logLevel: "silent",
    database: "lexora_test",
    appPassword,
    ownerPassword,
  }),
  ENV_MODE,
);

console.log("\nNext: npm run db:up && npm run db:migrate && npm run db:migrate:test");
